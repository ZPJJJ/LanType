def schema_policy() -> None:
    # Explicit empty values prevent a 1.0.0 installation from auto-opening leftover optional models.
    for parent in ["rime_ice", "rime_chinese"]:
        for p in (ASSETS / parent).glob("*.schema.yaml"):
            text = p.read_text()
            text = re.sub(r"^(\s*)ngram_model:.*$", r'\1ngram_model: ""  # Commercial edition: dictionary/local learning only', text, flags=re.M)
            text = re.sub(r"^cylm:\n(?:[ \t].*\n|\n)*", "", text, flags=re.M)
            text = text.replace("  language: wanxiang-lts-zh-hans", '  language: ""  # No external grammar model')
            text = text.replace("  offer_homophone_tails: true", "  offer_homophone_tails: false")
            p.write_text(text)
    p = ASSETS / "rime/default.yaml"
    text = p.read_text().replace("  - schema: wubi86_pinyin\n", "").replace("  - schema: wubi86\n", "")
    p.write_text(text)


def original_sounds() -> None:
    raw = ROOT / "app/src/main/res/raw"
    # Entirely synthesized waveforms. No recorded keyboard, game, or third-party samples.
    names = sorted(p.stem for p in raw.glob("kb_*.wav"))
    for index, name in enumerate(names):
        rate, duration = 22050, (0.09 if "voice" in name else 0.035)
        frequency = 420 + index * 53
        samples = []
        for n in range(int(rate * duration)):
            t = n / rate
            envelope = math.sin(math.pi * n / (rate * duration)) ** 2 * math.exp(-t * 55)
            value = envelope * (math.sin(2 * math.pi * frequency * t) + 0.25 * math.sin(2 * math.pi * frequency * 2.01 * t))
            samples.append(int(max(-1, min(1, value * 0.18)) * 32767))
        with wave.open(str(raw / (name + ".wav")), "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
            w.writeframes(struct.pack("<" + "h" * len(samples), *samples))


def public_suffix() -> None:
    """Encode the editable MPL-2.0 list, retaining exact rule and exception order."""
    lines = (HERE / "source_data/public-suffix-list.txt").read_text().splitlines()
    rows = [line for line in lines if line and not line.startswith("//")]
    normal = ("\n".join(line for line in rows if not line.startswith("!")) + "\n").encode()
    exceptions = ("\n".join(line[1:] for line in rows if line.startswith("!")) + "\n").encode()
    (ASSETS / "PublicSuffixDatabase.list").write_bytes(
        struct.pack(">I", len(normal)) + normal + struct.pack(">I", len(exceptions)) + exceptions)


