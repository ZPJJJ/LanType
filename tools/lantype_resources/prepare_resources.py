def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source(name: str) -> bytes:
    path = HERE / "source_data" / (name + ".gz")
    data = gzip.decompress(path.read_bytes())
    lock = json.loads((HERE / "sources.lock.json").read_text())
    expected = next(x for x in lock["sources"] if x["name"] == name)["sha256"]
    if digest(data) != expected:
        raise ValueError(f"Source checksum mismatch: {name}")
    return data


def write(relative: str, data: str | bytes) -> None:
    path = ASSETS / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data.encode() if isinstance(data, str) else data)


def gz(data: str | bytes) -> bytes:
    return gzip.compress(data.encode() if isinstance(data, str) else data, mtime=0)


